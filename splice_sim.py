"""Replace SimulateIso14443aTagAID in iso14443a.c with eajet_sim.c."""
from pathlib import Path
import argparse
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from gtink.replay import SETS

SRC = Path(r"C:\ProxSpace\pm3\proxmark3\armsrc\iso14443a.c")
NEW = Path(r"O:\tij gt 1000\proxmark_patch\eajet_sim.c")
HEADER = SRC.parent / "eajet_sets.h"

VALID_SETS = ("A", "B", "C", "FACTORY", "E", "S1", "S2", "S3", "S4")
SET_ORDER = ("A", "B", "C", "factory", "E", "S1", "S2", "S3", "S4")


def _c_array(name: str, rows: list[bytes], width: int) -> str:
    """Format a two-dimensional C array of bytes."""
    out = [f"static const uint8_t {name}[{len(rows)}][{width}] = {{"]
    for row in rows:
        if len(row) != width:
            raise ValueError(f"{name}: row length {len(row)} != {width}")
        out.append("    {")
        for start in range(0, width, 12):
            chunk = row[start:start + 12]
            out.append("        " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
        out.append("    },")
    out.append("};")
    return "\n".join(out)


def write_header() -> None:
    """Write all replay states next to iso14443a.c for the C emulator."""
    sets = [SETS[name] for name in SET_ORDER]
    names = ", ".join(f'"{name}"' for name in SET_ORDER)
    parts = [
        "// Auto-generated by splice_sim.py from gtink/replay.py. Do not edit.",
        "#ifndef EAJET_SETS_H",
        "#define EAJET_SETS_H",
        f"#define EAJET_SET_COUNT {len(sets)}",
        "",
        _c_array("eajet_file0004", [s.file0004 for s in sets], 188),
        "",
        _c_array("eajet_file0003", [s.file0003 for s in sets], 32),
        "",
        _c_array("eajet_secure", [s.secure for s in sets], 88),
        "",
        _c_array("eajet_ch6", [s.challenge_0006 for s in sets], 4),
        "",
        _c_array("eajet_ch7", [s.challenge_0007 for s in sets], 4),
        "",
        f"static const char *const eajet_set_names[EAJET_SET_COUNT] = {{ {names} }};",
        "",
        "#endif",
        "",
    ]
    HEADER.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"header={HEADER} sets={names}")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--set", choices=VALID_SETS, default="C",
                    help="state yang di-replay (default C)")
    args = ap.parse_args()

    write_header()

    src = SRC.read_text(encoding="utf-8", newline="")
    new = NEW.read_text(encoding="utf-8", newline="")

    marker = "void SimulateIso14443aTagAID("
    count = src.count(marker)
    if count != 1:
        sys.exit(f"expected exactly one definition, found {count}")

    marker_pos = src.index(marker)
    end = len(src.rstrip())
    if src[end - 1] != "}":
        sys.exit("last non-whitespace character is not '}'")

    # Find the beginning of a previously injected block so helper functions
    # and selector defines do not accumulate on every splice.
    begin_marker = "// === EAJET SIM BEGIN ==="
    starts = []
    pos = src.rfind(begin_marker, 0, marker_pos)
    if pos != -1:
        starts.append(pos)
    for token in ('#include "eajet_sets.h"', "#define EAJET_SET_"):
        pos = src.rfind(token, 0, marker_pos)
        if pos != -1:
            starts.append(pos)
    start = min(starts) if starts else marker_pos

    # Inject the compile-time set selector before the function body.  Strip
    # selectors left behind by earlier splices first, otherwise a previous
    # --set A would keep winning over a later --set C.
    prefix = re.sub(r"(?m)^#define EAJET_SET_[A-Z0-9]+\r?\n", "", src[:start])
    define = f"#define EAJET_SET_{args.set}\n"
    new = begin_marker + "\n" + define + new

    tail = src[end:]
    if not new.endswith("\n"):
        new += "\n"

    SRC.write_text(prefix + new + tail, encoding="utf-8", newline="")
    print(f"set={args.set} replaced {end - start} bytes with {len(new)} bytes")
    print(f"new file size: {SRC.stat().st_size}")


if __name__ == "__main__":
    main()
